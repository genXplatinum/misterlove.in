/* ------------------------------------------------------------------
   Lookups and derived facts. Nothing here is maintained by hand.
   ------------------------------------------------------------------ */

export const getBook = (slug) => books.find((book) => book.slug === slug);

/** Canonical client-side path for a book, or one study inside it. */
export const bookPathOf = (book, study) => (
  study ? `/books/${book.slug}/${study}` : `/books/${book.slug}`
);

/**
 * Studies actually published. A book announces the studies planned for it long
 * before they are written; everything that makes a promise to a reader or a
 * crawler counts these, never the planned total.
 */
export const liveStudiesOf = (book) => book.live ?? book.studies;

/** Whether more studies on this book are still to come. */
export const isOpen = (book) => liveStudiesOf(book) < book.studies;

/**
 * The full contents of a shelf entry: its published studies, plus any
 * announced-but-unwritten ones from the outline. Given the loaded data file,
 * the written study always wins — the outline only fills the gap after it.
 */
export const studiesOf = (book, studies) => {
  const written = new Map((studies ?? []).map((s) => [s.n, s]));
  const planned = book.outline ?? [];
  const total = Math.max(book.studies, written.size, ...planned.map((o) => o.n), 0);

  return Array.from({ length: total }, (_, i) => {
    const n = i + 1;
    const study = written.get(n);
    if (study) return { ...study, n, live: true };
    const o = planned.find((x) => x.n === n);
    return {
      n,
      live: false,
      slug: null,
      label: o?.label ?? '',
      title: o?.title ?? `Study ${n}`,
      sentence: o?.sentence ?? '',
      lead: o?.blurb ?? '',
    };
  });
};

/** One study by its slug, from a loaded data file. */
export const getStudy = (studies, slug) => (studies ?? []).find((s) => s.slug === slug);

/** Totals for the shelf header — published work only. */
export const booksTotals = {
  books: books.length,
  studies: books.reduce((a, b) => a + liveStudiesOf(b), 0),
  words: books.reduce((a, b) => a + b.words, 0),
  axioms: books.reduce((a, b) => a + (b.axioms ?? 0), 0),
};
